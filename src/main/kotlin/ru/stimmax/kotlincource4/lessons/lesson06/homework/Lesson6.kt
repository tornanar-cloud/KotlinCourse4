/*
Задание 2: "Расчет возраста питомца"

Создайте функцию, которая преобразует возраст собаки в "человеческие" годы.
До 2 лет каждый год собаки равен 10.5 человеческим годам, после - каждый год равен 4 человеческим годам.
Результат распечатай в консоль.

12
126
 */
fun dogsYearsToHumanYears(age: Int) {
    if (age !in 1..50) {
        println("Возраст должен быть от 1 до 50 лет включительно")
    } else {
        val result = if (age <= 2) {
            age * 10.5
        } else {
            (2 * 10.5) + (age - 2) * 4.0
        }.toInt()
        println("${age} лет собаки равно ${result} лет человека")
    }
}


