Задание 7: "Подбор одежды по погоде"

Напишите функцию, которая на основе температуры воздуха рекомендует тип одежды: "куртка и шапка" при температуре ниже +10, "ветровка" от +10 до +18
градусов включительно и "футболка и шорты" при температуре выше +18 градусов. При температурах ниже -30 и выше +35 рекомендуйте не выходить из дома.
*/

fun recommendClothing(temperature: Double) {
    if (temperature !in -100.0..100.0) {
        println("температура должна быть от -100 до 100 включительно")
    } else {
        val message: String = when {
            temperature in -30.0..<10.0 -> "Куртка и шапка"
            temperature in 10.0..18.0 -> "Ветровка"
            temperature > 18.0 && temperature <= 35 -> "Футболка и майка"
            else -> "Не рекомендуется выходить"
        }
        println(message)
    }
}

